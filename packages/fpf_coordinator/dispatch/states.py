    DEV_HANDOFF_PENDING = "DEV_HANDOFF_PENDING"
    TRUSTED_DEV_VALIDATION = "TRUSTED_DEV_VALIDATION"
    QA_PLAN_FREEZE_PENDING = "QA_PLAN_FREEZE_PENDING"
