    QA_RUNNING = "QA_RUNNING"
    QA_EVIDENCE_REVIEW_PENDING = "QA_EVIDENCE_REVIEW_PENDING"
    TRUSTED_QA_VALIDATION = "TRUSTED_QA_VALIDATION"
    QA_PASSED_AWAITING_OWNER_MERGE = "QA_PASSED_AWAITING_OWNER_MERGE"
    HUMAN_GATE_MERGE = "HUMAN_GATE_MERGE"
    MERGE_VERIFICATION = "MERGE_VERIFICATION"
