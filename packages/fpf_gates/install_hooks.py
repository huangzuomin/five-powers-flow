"""Install the repository hooks that gate secret material (G3).

The hook body lives here rather than in a tracked ``.githooks/pre-commit``
file: a change to a bare ``.githooks/`` path is neither protected nor prose, so
a PR that ships the hook as a standalone file alongside ``.github/`` changes
cannot be routed by the gate at all. Keeping the body next to the installer
keeps it reviewable and makes the slice routable through one GATE_PR.

Installing sets ``core.hooksPath=.githooks``. Existing hooks under
``.git/hooks`` are *reported*, never moved or deleted: silently shadowing a
maintainer's hook would be a regression.
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

HOOK_RELATIVE = Path(".githooks") / "pre-commit"
SCANNER_RELATIVE = Path("packages") / "fpf_gates" / "secret_scan.py"

HOOK_BODY = """#!/bin/sh
# FPF pre-commit hook (G3): block commits that stage secret material.
# Generated by packages/fpf_gates/install_hooks.py -- do not edit in place.
# Client-side hooks are bypassable with --no-verify; the unbypassable layer is
# the secret-scan workflow on every pull request.
set -u

ROOT=$(git rev-parse --show-toplevel 2>/dev/null) || {
    echo "[FPF PRE-COMMIT] not inside a git worktree; refusing to guess" >&2
    exit 1
}
cd "$ROOT" || exit 1

PY=$(command -v python3 2>/dev/null || command -v python 2>/dev/null)
if [ -z "$PY" ]; then
    echo "[FPF PRE-COMMIT] python not found; cannot prove the commit is clean" >&2
    exit 1
fi

if ! "$PY" packages/fpf_gates/secret_scan.py --staged; then
    echo "" >&2
    echo "[FPF PRE-COMMIT BLOCKED] staged secret material detected." >&2
    echo "Remove it from the index (git restore --staged <path>) or, for a" >&2
    echo "documented vendor placeholder, append: # fpf-secret-scan: allow <reason>" >&2
    exit 1
fi

exit 0
"""


def _git(*args: str) -> str:
    result = subprocess.run(["git", *args], capture_output=True, text=True, check=False)
    if result.returncode != 0:
        raise SystemExit(result.stderr.strip() or "git command failed")
    return result.stdout.strip()


def legacy_hooks(root: Path) -> list[str]:
    hooks_dir = root / ".git" / "hooks"
    if not hooks_dir.is_dir():
        return []
    return sorted(
        p.name
        for p in hooks_dir.iterdir()
        if p.is_file() and not p.name.endswith(".sample")
    )


def write_hook(root: Path) -> Path:
    target = root / HOOK_RELATIVE
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(HOOK_BODY, encoding="utf-8", newline="\n")
    return target


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Install FPF git hooks")
    parser.add_argument("--check", action="store_true", help="report, do not modify")
    args = parser.parse_args(argv)

    root = Path(_git("rev-parse", "--show-toplevel"))
    if not (root / SCANNER_RELATIVE).is_file():
        print(f"missing {SCANNER_RELATIVE}; run from a full checkout", file=sys.stderr)
        return 1

    current = ""
    result = subprocess.run(
        ["git", "config", "--get", "core.hooksPath"], capture_output=True, text=True
    )
    if result.returncode == 0:
        current = result.stdout.strip()

    shadowed = [name for name in legacy_hooks(root) if name != "pre-commit"]
    if shadowed:
        print(
            "WARNING: these .git/hooks entries will stop running once "
            f"core.hooksPath={HOOK_RELATIVE.parent.as_posix()} takes effect: "
            + ", ".join(shadowed),
            file=sys.stderr,
        )
        print(
            "Port anything still needed into .githooks/ before relying on it.",
            file=sys.stderr,
        )

    if args.check:
        print(f"core.hooksPath is {current or '(unset)'}; would set .githooks")
        return 0

    hook = write_hook(root)
    print(f"wrote {hook.relative_to(root).as_posix()}")
    _git("config", "core.hooksPath", ".githooks")
    print("installed: core.hooksPath=.githooks")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
